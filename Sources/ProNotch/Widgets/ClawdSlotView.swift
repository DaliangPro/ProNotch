/// 把像素网格铺成两条路径（主体一条、眼睛一条）后一次性填色。
///
/// 逐格 `fill` 会在 54×38 = 2052 个格子上各发一次绘制命令，
/// 按颜色合并成 Path 之后只剩两次。`drawingGroup()` 再把整只离屏栅格化，
/// 工作态每 0.15 秒换一帧，这两步省下的是实打实的持续开销。
private struct ClawdCanvas: View {
    let grid: [String]

    var body: some View {
        Canvas { ctx, size in
            let cellW = size.width / CGFloat(ClawdSprite.cols)
            let cellH = size.height / CGFloat(ClawdSprite.rows)
            var body = Path()
            var eyes = Path()
            for (y, row) in grid.enumerated() {
                for (x, ch) in row.enumerated() where ch != "." {
                    let rect = CGRect(x: CGFloat(x) * cellW, y: CGFloat(y) * cellH,
                                      width: cellW, height: cellH)
                    if ch == "o" { eyes.addRect(rect) } else { body.addRect(rect) }
                }
            }
            ctx.fill(body, with: .color(ClawdSprite.bodyColor))
            ctx.fill(eyes, with: .color(ClawdSprite.eyeColor))
        }
        .drawingGroup()
    }
}

/// 收起态槽位里的 Claude Code 工作状态：Clawd + 指示灯。
///
/// 空闲 = 绿灯 + 站着不动；工作中 = 黄灯 + 原地走动（官方四帧循环，含自带的弹跳）。
///
/// 空闲态刻意**不做**「偶尔左右张望」：那需要一个全天候跑的亚秒级定时器，
/// 而这个槽位一天里绝大多数时间都是空闲的——为一个眼神挂个常驻心跳，
/// 正是之前「两侧全关仍在空转」那类问题的来源。工作中才有动画，动画才有定时器。
struct ClawdSlotView: View {
    let working: Bool

    /// 每帧 0.15 秒 → 一步 0.6 秒，是正常走路的节奏。
    /// 早先两帧交替时用的 0.38 秒，放在四帧循环上会慢成慢动作
    private static let frameInterval: TimeInterval = 0.15
    /// 宽度不是按可用空间取的，是**按体量对齐 Codex 槽位**（大梁老师反馈 36pt 太大，28pt 拍板）
    private static let spriteWidth: CGFloat = 28
    /// 高度由原件比例定死（54:38），别自己填数——填错会把 Clawd 拉扁或抻长，
    /// 而这个尺寸下肉眼看不出来，只有 `test与Clawd槽位同高` 拦得住
    private static let spriteHeight: CGFloat = 28.0 / CGFloat(ClawdSprite.cols) * CGFloat(ClawdSprite.rows)

    var body: some View {
        HStack(spacing: 4) {
            if working {
                // TimelineView 只在这一支里存在：熄灯即整支下树，定时器随之消失
                TimelineView(.periodic(from: .now, by: Self.frameInterval)) { ctx in
                    let tick = Int(ctx.date.timeIntervalSinceReferenceDate / Self.frameInterval)
                    // 取模前先取绝对值：参考日期之前 tick 为负，负数取模在 Swift 里也是负的，会越界
                    sprite(ClawdSprite.walking[abs(tick) % ClawdSprite.walking.count])
                }
            } else {
                sprite(ClawdSprite.standing)
            }
            Circle()
                .fill(working ? Color(hex: "#FFCC00") : Color(hex: "#34C759"))
                .frame(width: 6, height: 6)
        }
        .accessibilityLabel(working ? "Claude Code 工作中" : "Claude Code 空闲")
    }

    private func sprite(_ grid: [String]) -> some View {
        ClawdCanvas(grid: grid)
            .frame(width: Self.spriteWidth, height: Self.spriteHeight)
    }
}
